// Generates skills/piano-score-to-musicxml/scripts/core/qinban-core.mjs from lib/, so the
// published Skill runs the app's own score validation, MusicXML/MIDI export and tempo
// rules instead of hand-copied files that drift. Run after changing any of those lib
// modules; tests/skill-core.test.mjs fails while the committed file is stale.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
export const SKILL_CORE =
  "skills/piano-score-to-musicxml/scripts/core/qinban-core.mjs";
// Everything the Skill scripts import from the app.
const ENTRY = `
export { validateScore, scoreMeasureIndex } from "./lib/score.mjs";
export { exportMusicXML, exportMidi, MUSICXML_DIVISIONS } from "./lib/exporters.mjs";
export { performanceNotes } from "./lib/note-effects.mjs";
export { recognitionTempo, validateTempoEvidence } from "./lib/recognition-tempo.mjs";
`;
const HEADER = `// Generated by scripts/build-skill-core.mjs from the 琴伴 lib/ sources. Do not edit;
// change lib/ and regenerate with: node scripts/build-skill-core.mjs
`;

export async function buildSkillCore() {
  const result = await build({
    absWorkingDir: root,
    stdin: {
      contents: ENTRY,
      resolveDir: root,
      sourcefile: "skill-core-entry.mjs",
    },
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    packages: "external",
    charset: "utf8",
    legalComments: "none",
    write: false,
    metafile: true,
    logLevel: "silent",
  });
  const external = new Set(
    Object.values(result.metafile.outputs)
      .flatMap((o) => o.imports)
      .filter((i) => i.external)
      .map((i) => i.path.match(/^(@[^/]+\/[^/]+|[^/]+)/)[1]),
  );
  const skill = JSON.parse(
    await readFile(
      new URL(
        "../skills/piano-score-to-musicxml/package.json",
        import.meta.url,
      ),
      "utf8",
    ),
  );
  const missing = [...external].filter(
    (name) =>
      !name.startsWith("node:") && !(name in (skill.dependencies || {})),
  );
  if (missing.length)
    throw Error(
      `Skill package.json is missing dependencies: ${missing.join(", ")}`,
    );
  return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  await writeFile(
    new URL("../" + SKILL_CORE, import.meta.url),
    await buildSkillCore(),
  );
