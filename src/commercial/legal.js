async function load() {
  let info;
  try {
    const response = await fetch("/api/v1/legal", {
      credentials: "omit",
      cache: "no-store",
    });
    if (!response.ok) throw new Error();
    info = await response.json();
  } catch {
    info = { complete: false, processors: [] };
  }
  const identity = info.operatorName
    ? `<p>服务运营方：${esc(info.operatorName)}</p>`
    : "";
  const contact = info.contactEmail
    ? `<p>联系邮箱：<a href="mailto:${esc(info.contactEmail)}">${esc(info.contactEmail)}</a></p>`
    : '<p>联系方式请查看<a href="/#support">帮助与反馈</a>。</p>';
  const processors = (info.processors || [])
    .map(
      (p) =>
        `<li><strong>${esc(p.name)}</strong>：${esc(p.purpose)} · <a href="${esc(p.privacyUrl)}" rel="noopener noreferrer">隐私说明</a></li>`,
    )
    .join("");
  root.innerHTML = layout({
    body: `<article class="commerce-card legal-document"><h1>${privacy ? "隐私政策" : "用户协议"}</h1><p class="commerce-muted">更新日期：2026 年 11 月 12 日</p>${identity}${!info.complete ? '<p class="commerce-notice">正式服务资料尚未补齐，本页为开放前说明。请在购买前核对运营方、联系邮箱及服务提供方信息。</p>' : ""}${privacy ? privacyBody : termsBody}<h2>服务提供方</h2>${processors ? `<ul>${processors}</ul>` : "<p>服务提供方信息将在正式开放前公布。</p>"}${contact}<p><a href="${privacy ? "/terms.html" : "/privacy.html"}">${privacy ? "查看用户协议" : "查看隐私政策"}</a> · <a href="/">返回琴伴</a></p></article>`,
  });
}
